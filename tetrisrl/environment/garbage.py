"""Incoming garbage queue, cancellation, and insertion.

Model
-----
An attack generated by a player first *cancels* pending incoming garbage (the
oldest entries first, partially if needed); only the remainder is sent to the
opponent, where it is appended to that player's pending queue with a configurable
``ready_in`` delay.  When a piece locks, every entry whose delay has elapsed is
inserted from the bottom, each batch sharing a hole column (TETR.IO-style
"clean" garbage) unless ``hole_mode="per_row"`` or ``messiness`` applies.

The RNG used for holes is owned by the player receiving garbage, so a replay seed
is enough to reproduce insertion order exactly.
"""

from __future__ import annotations

import random
from dataclasses import dataclass, field
from typing import Iterable, List, Optional, Tuple

from .board import Board
from .ruleset import GarbageConfig


@dataclass
class GarbageEntry:
    amount: int
    hole: int
    ready_in: int = 0
    batch_id: int = 0

    def __post_init__(self) -> None:
        if self.amount <= 0:
            raise ValueError("garbage amount must be positive")

    def to_dict(self) -> dict:
        return {"amount": self.amount, "hole": self.hole, "ready_in": self.ready_in, "batch_id": self.batch_id}

    @classmethod
    def from_dict(cls, data: dict) -> "GarbageEntry":
        return cls(amount=int(data["amount"]), hole=int(data["hole"]), ready_in=int(data.get("ready_in", 0)), batch_id=int(data.get("batch_id", 0)))


class GarbageQueue:
    def __init__(self, config: GarbageConfig, width: int = 10, seed: int = 0) -> None:
        self.config = config
        self.width = width
        self._rng = random.Random(seed)
        self.entries: List[GarbageEntry] = []
        self._next_batch_id = 0
        self.total_received = 0
        self.total_cancelled = 0
        self.total_inserted = 0

    # -- queueing ----------------------------------------------------------
    def _pick_hole(self) -> int:
        return self._rng.randrange(self.width)

    def add(self, amount: int, ready_in: Optional[int] = None) -> int:
        """Queue ``amount`` garbage lines, returning the amount actually queued."""
        if amount <= 0:
            return 0
        ready = self.config.insertion_delay_pieces if ready_in is None else ready_in
        queued = 0
        while amount > 0:
            chunk = min(amount, self.config.max_chunk)
            # Respect the queue cap.
            cap = self.config.queue_cap
            current = self.total()
            if current >= cap:
                break
            chunk = min(chunk, cap - current)
            if chunk <= 0:
                break
            entry = GarbageEntry(
                amount=chunk,
                hole=self._pick_hole(),
                ready_in=ready,
                batch_id=self._next_batch_id,
            )
            self._next_batch_id += 1
            self.entries.append(entry)
            amount -= chunk
            queued += chunk
        self.total_received += queued
        return queued

    def total(self) -> int:
        return sum(e.amount for e in self.entries)

    def __len__(self) -> int:
        return len(self.entries)

    def is_empty(self) -> bool:
        return not self.entries

    def peek(self, n: int = 5) -> List[GarbageEntry]:
        return self.entries[:n]

    # -- time --------------------------------------------------------------
    def tick(self, pieces: int = 1) -> None:
        for entry in self.entries:
            entry.ready_in = max(0, entry.ready_in - pieces)

    def ready_entries(self) -> List[GarbageEntry]:
        return [e for e in self.entries if e.ready_in <= 0]

    # -- cancellation ------------------------------------------------------
    def cancel(self, attack: int) -> Tuple[int, int]:
        """Cancel incoming garbage with ``attack``; return (cancelled, remaining)."""
        cancelled = 0
        remaining = attack
        while remaining > 0 and self.entries:
            entry = self.entries[0]
            take = min(entry.amount, remaining)
            entry.amount -= take
            cancelled += take
            remaining -= take
            if entry.amount == 0:
                self.entries.pop(0)
        self.total_cancelled += cancelled
        return cancelled, remaining

    # -- insertion ---------------------------------------------------------
    def pop_ready(self) -> List[GarbageEntry]:
        ready = [e for e in self.entries if e.ready_in <= 0]
        if ready:
            self.entries = [e for e in self.entries if e.ready_in > 0]
        return ready

    def tank(self, board: Board, cap: int) -> Tuple[int, List[dict]]:
        """Insert up to ``cap`` ready garbage lines (TETR.IO ``tank()``).

        Entries are consumed in FIFO order; leftovers stay queued for the next
        tank.  Each entry shares one hole column for its lines, with
        ``messiness_within`` allowing a reroll.
        """
        inserted = 0
        events: List[dict] = []
        cap = max(0, min(cap, self.config.tank_cap_max))
        while inserted < cap and self.entries and self.entries[0].ready_in <= 0:
            entry = self.entries[0]
            take = min(entry.amount, cap - inserted)
            hole = entry.hole
            overflow = False
            for _ in range(take):
                if self.config.messiness_within > 0.0 and self._rng.random() < self.config.messiness_within:
                    hole = self._pick_hole()
                overflow = board.insert_garbage(1, hole) or overflow
            inserted += take
            entry.amount -= take
            self.total_inserted += take
            events.append(
                {
                    "type": "garbage_insert",
                    "amount": take,
                    "hole": entry.hole,
                    "batch_id": entry.batch_id,
                    "overflow": overflow,
                }
            )
            if entry.amount <= 0:
                self.entries.pop(0)
                if self.config.messiness_change > 0.0 and self._rng.random() < self.config.messiness_change:
                    self.reroll_next_hole()
        return inserted, events

    def reroll_next_hole(self) -> None:
        for entry in self.entries:
            if entry.ready_in <= 0:
                new_hole = self._pick_hole()
                if self.config.messiness_nosame:
                    while new_hole == entry.hole and self.width > 1:
                        new_hole = self._pick_hole()
                entry.hole = new_hole
                break

    def insert_into(self, board: Board) -> Tuple[int, List[dict]]:
        """Insert all ready garbage into ``board``.

        Returns ``(inserted_lines, events)``; an event describes the batch hole
        and size for replay/UI purposes.
        """
        ready = self.pop_ready()
        inserted = 0
        events: List[dict] = []
        for entry in ready:
            rows: List[int] = []
            # TETR.IO-style clean garbage: one hole for the whole batch, unless
            # messiness/ per-row mode is configured.
            hole = entry.hole
            for i in range(entry.amount):
                if self.config.hole_mode == "per_row" and i > 0:
                    hole = self._pick_hole()
                elif self.config.messiness_within > 0.0 and self._rng.random() < self.config.messiness_within:
                    hole = self._pick_hole()
                rows.append(hole)
            overflow = False
            # Insert one row at a time so a multi-row batch keeps its order.
            for hole_col in rows:
                overflow = board.insert_garbage(1, hole_col) or overflow
            inserted += len(rows)
            self.total_inserted += len(rows)
            events.append({"type": "garbage_insert", "amount": len(rows), "hole": entry.hole, "batch_id": entry.batch_id, "overflow": overflow})
        return inserted, events

    # -- serialisation -----------------------------------------------------
    def state_dict(self) -> dict:
        return {
            "entries": [e.to_dict() for e in self.entries],
            "next_batch_id": self._next_batch_id,
            "total_received": self.total_received,
            "total_cancelled": self.total_cancelled,
            "total_inserted": self.total_inserted,
            "rng_state": self._rng.getstate(),
        }

    def load_state_dict(self, state: dict) -> None:
        self.entries = [GarbageEntry.from_dict(d) for d in state["entries"]]
        self._next_batch_id = int(state["next_batch_id"])
        self.total_received = int(state.get("total_received", 0))
        self.total_cancelled = int(state.get("total_cancelled", 0))
        self.total_inserted = int(state.get("total_inserted", 0))
        self._rng.setstate(state["rng_state"])


@dataclass
class AttackExchange:
    """Result of exchanging one attack with a garbage queue."""

    attack: int = 0
    cancelled: int = 0
    sent: int = 0
    incoming_before: int = 0
    incoming_after: int = 0

    def to_dict(self) -> dict:
        return {
            "attack": self.attack,
            "cancelled": self.cancelled,
            "sent": self.sent,
            "incoming_before": self.incoming_before,
            "incoming_after": self.incoming_after,
        }
