"""Tetromino definitions and SRS rotation-state geometry.

Coordinate conventions used throughout the project
--------------------------------------------------
* ``x`` grows to the right (column 0 .. 9).
* ``y`` grows **downwards** (row 0 is the top of the 40-row board).
* A piece is stored as a list of ``(x, y)`` *cell offsets* inside its bounding
  box, plus the box origin ``(x, y)`` in board coordinates.
* Rotation states are numbered ``0, R, 2, L`` (0 = spawn, R = clockwise,
  2 = 180, L = counter-clockwise), matching the SRS naming used by
  TETR.IO kick tables.

The four state matrices are generated by rotating the spawn matrix clockwise,
so they are guaranteed to be consistent with the piece art.  The geometry is
the standard Super Rotation System geometry (I in a 4x4 box, O in a 2x2 box,
JLSTZ in a 3x3 box) which TETR.IO's SRS+ builds on.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Tuple

Cell = Tuple[int, int]

PIECE_NAMES: Tuple[str, ...] = ("I", "J", "L", "O", "S", "T", "Z")
PIECE_INDEX: Dict[str, int] = {name: i for i, name in enumerate(PIECE_NAMES)}

# Spawn matrices (row-major, ``X`` = filled).  These are the classic SRS spawn
# orientations.  Row 0 is the top of the bounding box.
SPAWN_MATRICES: Dict[str, Tuple[str, ...]] = {
    "I": ("....", "XXXX", "....", "...."),
    "J": ("X..", "XXX", "..."),
    "L": ("..X", "XXX", "..."),
    "O": ("XX", "XX"),
    "S": (".XX", "XX.", "..."),
    "T": (".X.", "XXX", "..."),
    "Z": ("XX.", ".XX", "..."),
}

BOX_SIZE: Dict[str, int] = {name: len(mat) for name, mat in SPAWN_MATRICES.items()}


def _cells_from_matrix(matrix: Tuple[str, ...]) -> Tuple[Cell, ...]:
    cells: List[Cell] = []
    for y, row in enumerate(matrix):
        for x, ch in enumerate(row):
            if ch == "X":
                cells.append((x, y))
    return tuple(cells)


def _rotate_matrix_cw(matrix: Tuple[str, ...]) -> Tuple[str, ...]:
    n = len(matrix)
    return tuple("".join(matrix[n - 1 - x][y] for x in range(n)) for y in range(n))


def _build_states() -> Dict[str, Tuple[Tuple[Cell, ...], ...]]:
    states: Dict[str, Tuple[Tuple[Cell, ...], ...]] = {}
    for name, spawn in SPAWN_MATRICES.items():
        mats = [spawn]
        for _ in range(3):
            mats.append(_rotate_matrix_cw(mats[-1]))
        states[name] = tuple(_cells_from_matrix(m) for m in mats)
    return states


#: ``CELLS[piece][rotation_state]`` -> tuple of ``(x, y)`` offsets in the box.
CELLS: Dict[str, Tuple[Tuple[Cell, ...], ...]] = _build_states()

#: Width/height of the occupied cells for every piece / state.
def bounds(piece: str, rotation: int) -> Tuple[int, int, int, int]:
    """Return ``(min_x, max_x, min_y, max_y)`` (inclusive) of the piece cells."""
    cells = CELLS[piece][rotation % 4]
    xs = [c[0] for c in cells]
    ys = [c[1] for c in cells]
    return min(xs), max(xs), min(ys), max(ys)


#: The left-most occupied column offset for each (piece, rotation).  Actions
#: address a placement by the piece's left-most occupied column, which makes
#: every reachable column expressible regardless of the rotation's offset.
LEFT_OFFSET: Dict[str, Tuple[int, int, int, int]] = {
    name: tuple(bounds(name, r)[0] for r in range(4)) for name in PIECE_NAMES
}

#: Spawn box origins.  The resulting cells sit in rows 19/20 (hidden row 19 and
#: the first visible row 20), matching TETR.IO's spawn area above the field.
SPAWN_X: Dict[str, int] = {name: 3 for name in PIECE_NAMES}
SPAWN_X["O"] = 4
SPAWN_Y: Dict[str, int] = {name: 18 for name in PIECE_NAMES}


@dataclass(frozen=True)
class ActivePiece:
    """A piece positioned on the board (box origin in board coordinates)."""

    name: str
    rotation: int
    x: int
    y: int

    def cells(self) -> Tuple[Cell, ...]:
        return tuple((self.x + cx, self.y + cy) for cx, cy in CELLS[self.name][self.rotation % 4])

    def moved(self, dx: int = 0, dy: int = 0, drot: int = 0) -> "ActivePiece":
        return ActivePiece(self.name, (self.rotation + drot) % 4, self.x + dx, self.y + dy)
